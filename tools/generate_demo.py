"""Generate deterministic, entirely fictional student data; never infer new scores for real rows."""
import csv
import json
import random
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SUBJECTS = ['math', 'reading', 'writing', 'physics', 'chemistry', 'biology', 'computer science', 'history']

def generate(count=5000, seed=20261027, output=None):
    if not 1 <= count <= 50000:
        raise ValueError('count must be between 1 and 50,000')
    path = Path(output) if output else ROOT / 'data/synthetic_students.csv'
    path.parent.mkdir(parents=True, exist_ok=True)
    # Deterministic fictional data only; this generator never creates credentials.
    rng = random.Random(seed)  # nosec B311
    background = ['gender', 'race/ethnicity', 'parental level of education', 'lunch', 'test preparation course']
    headers = ['student_id', 'cohort', *background, *(f'{subject} score' for subject in SUBJECTS)]
    with path.open('w', newline='', encoding='utf-8') as file:
        writer = csv.DictWriter(file, fieldnames=headers, lineterminator="\n"); writer.writeheader()
        for i in range(count):
            ability = rng.gauss(68, 14)
            row = {'student_id': f'SYN-{i + 1:05d}', 'cohort': f'Cohort-{i % 10 + 1:02d}',
                   'gender': rng.choice(['female', 'male', 'not specified']),
                   'race/ethnicity': rng.choice(['group A', 'group B', 'group C', 'group D', 'group E']),
                   'parental level of education': rng.choice(['high school', 'some college', "bachelor's degree", "master's degree"]),
                   'lunch': rng.choice(['standard', 'free/reduced']),
                   'test preparation course': rng.choice(['none', 'completed'])}
            # Background categories are generated independently from academic scores.
            row.update({f'{subject} score': max(0, min(100, round(ability + rng.gauss(0, 10)))) for subject in SUBJECTS})
            writer.writerow(row)
    return path

if __name__ == '__main__':
    generate()
    (ROOT / 'data/manifest.json').write_text(json.dumps({
        'dataset': 'synthetic_students.csv', 'records': 5000, 'subjects': SUBJECTS,
        'seed': 20261027, 'kind': 'entirely synthetic',
        'source': 'tools/generate_demo.py', 'license': 'MIT (generated by this project)',
        'purpose': 'Software testing and demonstration only; no real students or valid demographic findings.',
        'original_dataset': 'StudentsPerformance.csv is retained separately, unchanged; source and reuse terms remain unverified.'
    }, indent=2) + '\n')
